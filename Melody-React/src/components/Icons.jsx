export function Icon({ name, size = 20, className = '' }) {
  const paths = PATHS[name]
  if (!paths) return null
  const cls = `icon icon-${name}${className ? ` ${className}` : ''}`.trim()
  return (
    <svg
      className={cls}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {paths}
    </svg>
  )
}

